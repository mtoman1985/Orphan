        return ended_sponsorships_label;
      default:
        return key;
    }
  }
}

/// Extension for nullable AppLocalizations to safely call get
extension AppLocalizationsNullableExtension on AppLocalizations? {
  /// Get a localized string by key name with null safety
  String get(String key) {
    if (this == null) return key;
    return this!.getKey(key);
  }
}

/// Helper extension on BuildContext for easier access
extension AppLocalizationsContext on BuildContext {
  /// Get AppLocalizations instance with null safety
  AppLocalizations get l10n => AppLocalizations.of(this)!;
}
